import { CONSENT_VERSION, MARKETING_NOTICE, PRIVACY_NOTICE } from "./consent";
import type { Processor } from "./processors";

export type PrivacyOfficer = { name: string; title?: string | null; phone?: string | null; email?: string | null };

/**
 * 기본 개인정보 처리방침 — 개인정보 보호법 제30조·시행령 제31조의 필수 기재사항을 모두 담는다.
 * 기관명·연락처·보호책임자·실제 위탁/국외 이전 대상(lib/legal/processors)을 넣어 만든다.
 * 기관 사정(오프라인 수집, 추가 사업 등)이 다르면 기관이 직접 고쳐 쓴다 — 실 운영 전 법무 검토 권장.
 */
export function defaultPrivacyPolicy(ctx: {
  orgName: string;
  contactEmail?: string | null;
  contactAddress?: string | null;
  contactPhone?: string | null;
  officer?: PrivacyOfficer | null;
  processors?: Processor[];
}): string {
  const org = ctx.orgName;
  const processors = ctx.processors ?? [];
  const domestic = processors.filter((p) => !p.overseas);
  const overseas = processors.filter((p) => p.overseas);
  const officer = ctx.officer?.name
    ? [
        `- 성명: ${ctx.officer.name}${ctx.officer.title ? ` (${ctx.officer.title})` : ""}`,
        ctx.officer.phone ? `- 전화: ${ctx.officer.phone}` : "",
        ctx.officer.email ? `- 이메일: ${ctx.officer.email}` : "",
      ].filter(Boolean).join("\n")
    : "- [개인정보 보호책임자 지정 필요 — 관리자 화면 > 개인정보 보호에서 입력]";

  return `# 개인정보 처리방침

${org}(이하 "기관")는 「개인정보 보호법」에 따라 후원자의 개인정보를 보호하고 관련 고충을 신속하게 처리하기 위해 다음과 같이 개인정보 처리방침을 정합니다.

## 1. 개인정보의 처리 목적
- 후원 신청 접수, 결제 및 정기후원 관리
- 기부금영수증 발급과 국세청 연말정산 간소화 자료 제출
- 후원 관련 안내(결제 결과, 영수증, 약정 변경, 결제 실패)
- 마이페이지 계정 관리(가입한 경우)
- 기관 소식·캠페인 안내(별도 동의한 경우만)
- 1:1 결연 후원(결연을 신청한 경우)

## 2. 처리하는 개인정보 항목
- 필수: 이름, 휴대전화번호, 이메일
- 선택: 생년월일, 주소, 가입 경로
- 기부금영수증 신청 시: 주민등록번호(기업은 사업자등록번호) — 별도 동의
- 결제 시: 결제 수단과 승인 정보. 카드번호·계좌번호는 결제대행사가 직접 처리하며 기관은 받지 않습니다.
- 자동이체(현장 신청 포함) 시: 예금주, 은행명, 계좌번호 끝 4자리, 출금 동의 서명 또는 기록
- 결연 후원 시: 후원자가 쓴 편지
- 자동 수집: 접속 기록, IP 주소, 브라우저 저장값(7항)

## 3. 처리 및 보유 기간
- 후원 정보: 후원 종료(회원 탈퇴) 후 5년 — 기부금영수증 발급명세 보관 의무(「법인세법」 제112조의2, 「소득세법」 제160조의3)
- 주민등록번호: 기부금영수증 발급에 필요한 기간. 결제가 이뤄지지 않은 신청에 남은 번호는 결제가 취소되면 바로, 미결제 상태로 90일이 지나면 파기합니다.
- 마케팅 동의 정보: ${MARKETING_NOTICE.retention}
- 계정 정보: 회원 탈퇴 시까지

## 4. 개인정보의 제3자 제공
기관은 정보주체의 동의 또는 법률에 특별한 규정이 있는 경우에만 개인정보를 제3자에게 제공합니다.
- 국세청: 「소득세법」 등에 따른 연말정산 간소화 기부금 자료 제출(이름, 주민등록번호, 기부 금액)

## 5. 개인정보 처리의 위탁
기관은 원활한 업무를 위해 다음과 같이 개인정보 처리를 위탁하며, 수탁자가 개인정보를 안전하게 처리하도록 관리·감독합니다.
${processors.map((p) => `- ${p.name}: ${p.task}`).join("\n") || "- (없음)"}

## 6. 개인정보의 국외 이전
${overseas.length === 0 ? "기관은 개인정보를 국외로 이전하지 않습니다." : `서비스 운영을 위해 다음과 같이 개인정보를 국외에서 처리·보관합니다(「개인정보 보호법」 제28조의8). 국외 이전을 원하지 않으시면 개인정보 보호책임자에게 알려 주세요. 다만 이 경우 온라인 후원·계정 이용이 어려울 수 있습니다.
${overseas.map((p) => `- ${p.name}(${p.overseas!.site}) — 이전 국가: ${p.overseas!.country} / 항목: ${p.items} / 목적: ${p.task} / 시기·방법: ${p.overseas!.when}, ${p.overseas!.how} / 보유기간: 3항의 기간 또는 위탁 계약 종료 시까지`).join("\n")}`}
${domestic.length ? `
국내 수탁자: ${domestic.map((p) => p.name).join(", ")}` : ""}

## 7. 개인정보 자동 수집 장치의 설치·운영 및 거부
- 로그인 유지와 보안을 위해 쿠키를, 후원 신청 화면 개선(A/B 비교)을 위해 브라우저 저장소에 임의의 식별값을 저장합니다. 이 식별값으로 개인을 알아볼 수 없습니다.
- 브라우저 설정에서 쿠키·저장값을 지우거나 막을 수 있습니다. 쿠키를 막으면 로그인이 필요한 마이페이지를 쓸 수 없습니다.

## 8. 만 14세 미만 아동의 개인정보
기관은 만 14세 미만 아동의 후원 신청을 온라인으로 받지 않습니다. 보호자 명의로 후원해 주세요.

## 9. 개인정보의 파기 절차 및 방법
- 보유 기간이 끝나거나 처리 목적을 이룬 개인정보는 지체 없이 파기합니다.
- 전자 파일은 복구할 수 없는 방법으로 지우고(이름은 '익명'으로 바꾸고 연락처·주소·주민등록번호 등은 삭제), 종이 문서는 분쇄하거나 소각합니다.
- 다른 법령에 따라 보관해야 하는 정보는 그 법령이 정한 기간 동안 다른 정보와 분리해 보관합니다.

## 10. 정보주체와 법정대리인의 권리·의무 및 행사 방법
- 언제든 개인정보 열람, 정정·삭제, 처리정지, 동의 철회를 요구할 수 있습니다.
- 마이페이지에서 직접 정보를 고치고, 마케팅 수신 동의를 철회하고, 탈퇴할 수 있습니다. 또는 아래 보호책임자에게 서면·전화·이메일로 요구할 수 있으며, 기관은 지체 없이 조치합니다.
- 법령에서 보관을 정한 정보는 삭제를 요구하셔도 그 기간 동안 보관합니다.

## 11. 개인정보의 안전성 확보 조치
- 주민등록번호·결제 관련 키 암호화 저장, 전 구간 암호화 통신(HTTPS)
- 개인정보를 다루는 직원 최소화와 역할별 권한 관리, 관리자 2단계 인증
- 개인정보 처리 기록(접속·조회·다운로드) 보관과 점검
- 보유 기간이 지난 정보 자동 파기

## 12. 개인정보 보호책임자
${officer}
${ctx.contactEmail ? `- 기관 문의 이메일: ${ctx.contactEmail}` : ""}
${ctx.contactPhone ? `- 기관 전화: ${ctx.contactPhone}` : ""}
${ctx.contactAddress ? `- 주소: ${ctx.contactAddress}` : ""}

## 13. 권익침해 구제 방법
개인정보 침해에 대한 신고나 상담이 필요하시면 아래 기관에 문의하실 수 있습니다.
- 개인정보분쟁조정위원회: 1833-6972 (www.kopico.go.kr)
- 개인정보침해신고센터: 국번 없이 118 (privacy.kisa.or.kr)
- 대검찰청: 국번 없이 1301 (www.spo.go.kr)
- 경찰청: 국번 없이 182 (ecrm.police.go.kr)

## 14. 처리방침의 변경
이 방침은 ${CONSENT_VERSION}부터 적용합니다. 내용이 바뀌면 시행 7일 전부터 이 페이지에 알립니다.

*후원 신청 시 고지하는 수집·이용 목적: ${PRIVACY_NOTICE.purpose}*
`;
}

export function defaultTerms(ctx: { orgName: string }): string {
  return `# 이용약관

## 제1조 (목적)
본 약관은 ${ctx.orgName}(이하 "기관")이 제공하는 후원 서비스(이하 "서비스")의 이용과 관련하여 기관과 이용자(이하 "회원")의 권리·의무 및 책임사항을 규정합니다.

## 제2조 (정의)
- "회원"이라 함은 기관의 후원 서비스에 가입·이용하는 개인 또는 단체를 말합니다.
- "정기후원"은 매월 자동 결제되는 후원을 말합니다.
- "일시후원"은 1회성 후원을 말합니다.

## 제3조 (약정의 체결)
회원은 서비스 내에서 후원 약정을 체결할 수 있으며, 약정은 회원이 후원하기 버튼을 누른 시점에 성립됩니다.

## 제4조 (결제 및 해지)
- 정기후원은 매월 지정일에 자동 결제됩니다.
- 회원은 언제든지 마이페이지에서 약정을 일시중지하거나 해지할 수 있습니다.
- 결제 실패 시 최대 3회 재시도 후 약정이 자동 일시중지됩니다.

## 제5조 (기부금 영수증)
- 기부금 영수증은 매년 1월 국세청 연말정산 간소화 서비스를 통해 제공됩니다.
- 회원은 마이페이지에서 본인의 영수증을 개별 다운로드할 수 있습니다.

## 제6조 (약관의 변경)
본 약관은 관계 법령 변경이나 서비스 개선을 위해 변경될 수 있으며, 변경 시 7일 전 공지합니다.

*본 약관은 공개된 시점부터 효력을 가집니다.*
`;
}
